def j(path):
    return json.loads(path.read_text()) if path.exists() else None


def f(x, d=4):
    return "–" if x is None else f"{x:.{d}f}"


def s(x, d=4):
    return "–" if x is None else f"{x:+.{d}f}"


def c(lo_hi, d=4):
    return "–" if not lo_hi else f"[{lo_hi[0]:+.{d}f}, {lo_hi[1]:+.{d}f}]"


def lang_rows(path):
    if not path.exists():
        return None
    with path.open() as fh:
        return {r["stratum"]: {k: (float(v) if k not in ("kind", "axis", "language", "stratum", "ci_method") and v else v)
                               for k, v in r.items()}
                for r in csv.DictReader(fh) if r["kind"] == "start" and r["axis"] == "language"}


def base_rows(path):
    b = j(path)
    return None if b is None else {(r["language"], r["proposer"]): r for r in b["rows"] if r["kind"] == "start"}


def best(b, lang):
    return max((b[(lang, p)] for p in ("newline", "indent_change", "word_start") if (lang, p) in b), key=lambda r: r["f1"])


def ledger():
    path = FINAL / "logs/full_run_jobs.txt"
    jobs = {}
    if path.exists():
        for line in path.read_text().splitlines():
            if line and not line.startswith("#"):
                name, jid = line.split()[:2]
                jobs[name] = jid
    return jobs


