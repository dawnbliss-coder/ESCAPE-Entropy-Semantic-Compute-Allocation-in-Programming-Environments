"""Load bytes for the distillation experiment and cut them into <=512-byte windows.

Primary source is the extension corpus (corpus_ext/, disjoint from the evaluation set):
manifest_ext.parquet lists one row per file with a `split` column (train/val) and a
`source_path` that points at the materialized corpus_ext/<domain>/<file_id>.bin. The raw
.bin files are regenerated by stream_b/build_ext_corpus.py (they are gitignored), so this
loader also accepts any directory of *.bin files, and falls back to golden_fixtures/ for a
teacher-free local smoke test.

Windowing: a file of N bytes becomes ceil(N/512) non-overlapping windows of at most 512
bytes. Each window of k bytes becomes token ids [BOS] + [b+4 ...] (length k+1), and the
k positions 0..k-1 are the ones that predict a real byte (position j predicts token j+1;
there is no EOS, so the final position predicts nothing and is masked out).
"""

from __future__ import annotations

import random
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import torch

from escape_distill.student_blt import BOS_ID, BYTE_TOKEN_OFFSET, PAD_ID

MAX_BYTES = 512


@dataclass
class Sample:
    sample_id: str
    domain: str
    data: bytes


def _read_manifest(manifest_path: Path):
    import pandas as pd
    return pd.read_parquet(manifest_path)


def load_samples(source: str, split: str | None = None, limit: int | None = None,
                 domains: tuple[str, ...] | None = None, seed: int = 20260927) -> list[Sample]:
    """Return a list of Sample. `source` is one of:
      - a path to manifest_ext.parquet (uses its split column and source_path);
      - a directory of *.bin files (filename stem is the id, parent dir is the domain);
      - the literal 'golden' for golden_fixtures/.
    """
    src = Path(source)
    samples: list[Sample] = []

    if src.name.endswith(".parquet"):
        df = _read_manifest(src)
        root = src.parent
        if split is not None and "split" in df.columns:
            df = df[df["split"] == split]
        if domains is not None and "domain" in df.columns:
            df = df[df["domain"].isin(domains)]
        df = df.sort_values("file_id") if "file_id" in df.columns else df
        for _, row in df.iterrows():
            p = Path(row["source_path"]) if "source_path" in row else None
            if p is None or not p.exists():
                # fall back to the conventional layout next to the manifest
                p = root / str(row.get("domain", "")) / f"{row['file_id']}.bin"
            if not p.exists():
                continue
            samples.append(Sample(str(row["file_id"]), str(row.get("domain", "?")), p.read_bytes()))
            if limit and len(samples) >= limit:
                break
        return samples

    if source == "golden":
        src = Path("golden_fixtures")
    if src.is_dir():
        files = sorted(src.rglob("*.bin"))
        for p in files:
            samples.append(Sample(p.stem, p.parent.name, p.read_bytes()))
            if limit and len(samples) >= limit:
                break
        return samples

    raise ValueError(f"unrecognized data source: {source!r}")


def windows_from_bytes(data: bytes, max_bytes: int = MAX_BYTES):
    """Yield non-overlapping byte windows of length <= max_bytes."""
    for s in range(0, len(data), max_bytes):
        w = data[s:s + max_bytes]
        if w:
            yield w


def window_to_ids(window: bytes) -> np.ndarray:
    ids = np.empty(len(window) + 1, dtype=np.int64)
    ids[0] = BOS_ID
    ids[1:] = np.frombuffer(window, dtype=np.uint8).astype(np.int64) + BYTE_TOKEN_OFFSET
    return ids


def build_windows(samples: list[Sample], max_bytes: int = MAX_BYTES,
                  min_bytes: int = 1) -> list[np.ndarray]:
    """Flatten samples into a list of token-id arrays, one per window."""
    out = []
    for s in samples:
        for w in windows_from_bytes(s.data, max_bytes):
            if len(w) >= min_bytes:
                out.append(window_to_ids(w))
    return out


def collate(id_arrays: list[np.ndarray], device) -> dict:
    """Right-pad a list of token-id arrays to a batch.
    Returns input_ids [B, L], and a predict_mask [B, L] that is True at positions
    0..k-1 of a window with k real bytes (the positions that predict a real next byte)."""
    L = max(len(a) for a in id_arrays)
    B = len(id_arrays)
    input_ids = torch.full((B, L), PAD_ID, dtype=torch.long)
    predict_mask = torch.zeros((B, L), dtype=torch.bool)
    for i, a in enumerate(id_arrays):
        input_ids[i, : len(a)] = torch.from_numpy(a)
        # window has len(a)-1 real bytes; positions 0..len(a)-2 predict a real byte
        predict_mask[i, : len(a) - 1] = True
    return {"input_ids": input_ids.to(device), "predict_mask": predict_mask.to(device)}


class WindowLoader:
    """Deterministic, shuffled minibatches of windows."""

    def __init__(self, windows: list[np.ndarray], batch_size: int, device,
                 shuffle: bool = True, seed: int = 20260927):
        self.windows = windows
        self.batch_size = batch_size
        self.device = device
        self.shuffle = shuffle
        self.rng = random.Random(seed)

    def __len__(self):
        return (len(self.windows) + self.batch_size - 1) // self.batch_size

    def __iter__(self):
        order = list(range(len(self.windows)))
        if self.shuffle:
            self.rng.shuffle(order)
        for s in range(0, len(order), self.batch_size):
            idx = order[s:s + self.batch_size]
            yield collate([self.windows[i] for i in idx], self.device)


if __name__ == "__main__":
    import sys
    src = sys.argv[1] if len(sys.argv) > 1 else "golden"
    samples = load_samples(src, limit=20)
    print(f"samples: {len(samples)} from {src}")
    wins = build_windows(samples)
    print(f"windows: {len(wins)}; byte lengths (first 10): {[len(w) - 1 for w in wins[:10]]}")
    if wins:
        dev = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        batch = collate(wins[:4], dev)
        print("batch input_ids:", tuple(batch['input_ids'].shape),
              "predict positions:", int(batch['predict_mask'].sum()))
